function buildPostItem(dayIdx, slotIdx) {
  const topic = DAILY_TOPICS_30[dayIdx];
  const slotCfg = SLOT_CATEGORIES[slotIdx];
  const globalId = dayIdx * 15 + slotIdx + 1;

  const title = `${topic.name} — ${slotCfg.category} (${topic.day}-күн, ${slotCfg.slot})`;

  let specificBodyParagraph =
    `📌 **Не ушын бул әҳмийетли:** ${slotCfg.angle}. **${topic.name}** организмде ${topic.focus} ушын тийкарғы орын тутады.\n\n` +
    `🥗 **Дурыс аўқатланыў («Правильное питание») дереклери:** Күнделикли рационыңызға *${topic.foods}* сыяқлы тәбийғый өнимлерди киргизиў организмди таза витамин ҳәм микроэлементлер менен байытады.\n\n` +
    `💊 **Дәриханадағы препаратлар ҳәм БАДлар:** ${topic.drugs}.\n` +
    `👶 **6 айлықтан 6 жасқа шекемги перзентлер ушын:** ${topic.childNote}.\n\n` +
    `💡 **Фармацевт кеңеси (${slotCfg.slot}):** ${slotCfg.tip}`;

  const qaQuestion = `${topic.name} бойынша (${slotCfg.category.toLowerCase()} бағдарында) ең әҳмийетли қағыйда қандай?`;
  const qaAnswer =
    `${topic.name} қуралларын қабыл еткенде ${slotCfg.tip.charAt(0).toLowerCase() + slotCfg.tip.slice(1)} ` +
    `Ересеклер ҳәм 6 айлықтан 6 жасқа шекемги перзентлер ушын дозаны «Pintok Apteka» фармацевтинен анықлап алыўыңыз мүмкин.`;

  return {
    id: globalId,
    day: topic.day,
    slotKey: slotCfg.slot,
    category: slotCfg.category,
    badge: slotCfg.badge,
    photoUrl: slotCfg.photoUrl,
    title,
    body: specificBodyParagraph,
    qaQuestion,
    qaAnswer
  };
}

