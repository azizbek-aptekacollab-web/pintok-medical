class GroupStateManager {
  constructor(filePath = GROUP_STATE_FILE) {
    this.filePath = filePath;
    this.state = this.load();
  }

  load() {
    try {
      if (fs.existsSync(this.filePath)) {
        const raw = JSON.parse(fs.readFileSync(this.filePath, 'utf8'));
        return {
          groups: raw.groups || {},
          sentSchedules: raw.sentSchedules || {},
          postCounters: raw.postCounters || { slot10: 0, slot15: 0, slot19: 0 }
        };
      }
    } catch (e) {}
    return {
      groups: {},
      sentSchedules: {},
      postCounters: { slot10: 0, slot15: 0, slot19: 0 }
    };
  }

  save() {
    try {
      fs.writeFileSync(this.filePath, JSON.stringify(this.state, null, 2), 'utf8');
    } catch (e) {
      console.error("Failed to save group bot state:", e.message);
    }
  }

  registerGroup(chatId, title = "Pintok Apteka Group") {
    const key = String(chatId);
    const isNew = !this.state.groups[key];
    this.state.groups[key] = {
      chatId: Number(chatId),
      title: title || (this.state.groups[key] && this.state.groups[key].title) || "Pintok Apteka Group",
      updatedAt: new Date().toISOString(),
      active: true
    };
    this.save();
    return isNew;
  }

  getActiveGroups() {
    return Object.values(this.state.groups).filter(g => g.active !== false);
  }

  hasSentSchedule(dateStr, slotKey) {
    const dayMap = this.state.sentSchedules[dateStr] || {};
    return Boolean(dayMap[slotKey]);
  }

  markScheduleSent(dateStr, slotKey) {
    if (!this.state.sentSchedules[dateStr]) {
      this.state.sentSchedules[dateStr] = {};
    }
    this.state.sentSchedules[dateStr][slotKey] = new Date().toISOString();
    this.save();
  }

  nextPostIndex(slotKey, totalLength) {
    if (!this.state.postCounters) {
      this.state.postCounters = { slot10: 0, slot15: 0, slot19: 0 };
    }
    const idx = (this.state.postCounters[slotKey] || 0) % totalLength;
    this.state.postCounters[slotKey] = (idx + 1) % totalLength;
    this.save();
    return idx;
  }
}

function formatScheduledPost(slotKey, post) {
  let headerBadge = "🥗 **АЗАНҒЫ ПАЙДАЛЫ МАҒЛЫЎМАТ (10:00) — ДУРЫС АЎҚАТЛАНЫЎ ҲӘМ ВИТАМИНЛЕР**";
  if (slotKey === "15:00") {
    headerBadge = "💊 **КҮНДИЗГИ ПАЙДАЛЫ МАҒЛЫЎМАТ (15:00) — ӨЗБЕКСТАНДА САТЫЛЫП АТЫРҒАН ПАЙДАЛЫ БАДЛАР**";
  } else if (slotKey === "19:00") {
    headerBadge = "🌿 **КЕШКИ ПАЙДАЛЫ МАҒЛЫЎМАТ (19:00) — ШӨПТЕН ИСЛЕНГЕН ТӘБИЙҒЫЙ ДӘРИЛЕР ҲӘМ БАДЛАР**";
  }

  return (
    `${headerBadge}\n\n` +
    `📌 **${post.title}**\n\n` +
    `${post.body}\n\n` +
    `❓ **Сораў:** *${post.qaQuestion}*\n` +
    `✅ **Жуўап:** ${post.qaAnswer}\n\n` +
    `🏥 **«Pintok Apteka»** — Керекли дәрилер, витаминлер ҳәм таза БАДларды усы группаға жазып сорасаңыз болады!\n` +
    `🚚 **Бийпул доставка:** 09:00 ден 16:00 аралығында бесплатно!\n` +
    `📞 Телефон: **${CONTACT_PHONE}** (${CONTACT_PHONE_FORMATTED})`
  );
}

function getPostForSlot(slotKey, stateMgr) {
  if (slotKey === "08:00") {
    return MORNING_0800_TEXT;
  }
  if (slotKey === "10:00") {
    const idx = stateMgr.nextPostIndex("slot10", NUTRITION_AND_VITAMINS_POSTS.length);
    return formatScheduledPost("10:00", NUTRITION_AND_VITAMINS_POSTS[idx]);
  }
  if (slotKey === "15:00") {
    const idx = stateMgr.nextPostIndex("slot15", UZBEKISTAN_SUPPLEMENTS_POSTS.length);
    return formatScheduledPost("15:00", UZBEKISTAN_SUPPLEMENTS_POSTS[idx]);
  }
  if (slotKey === "19:00") {
    const idx = stateMgr.nextPostIndex("slot19", HERBAL_MEDICINES_POSTS.length);
    return formatScheduledPost("19:00", HERBAL_MEDICINES_POSTS[idx]);
  }
  return MORNING_0800_TEXT;
}

// Хызметкердиң клиентке жазған қысқа жуўабы ма ямаса клиенттиң сораўы/рецепти ме — тексериў
function isLikelyStaffReplyToCustomer(msg) {
  // Егер бул басқа адамның хабарына reply болса ҳәм ишинде сораў/рецепт болмай, тек жуўап сөзлери болса
  if (!msg.reply_to_message) return false;
  if (msg.photo || msg.document) return false;
  const text = (msg.text || "").trim().toLowerCase();
  if (!text) return false;
  const staffAnswerPatterns = [
    /^бар\b/,
    /^жоқ\b/,
    /^жок\b/,
    /^хазир\b/,
    /^ҳәзир\b/,
    /баҳасы/,
    /бахасы/,
    /сум\b/,
    /келип алың/,
    /жибердик/,
    /жеткерип беремиз/
  ];
  return staffAnswerPatterns.some(re => re.test(text));
}

function createGroupBotHandler({
  tgRequest = defaultGroupTgRequest,
  stateFile = GROUP_STATE_FILE,
  stateMgr = null,
  cooldownMs = 45000
} = {}) {
  stateMgr = stateMgr || new GroupStateManager(stateFile);
  const recentUserReplies = new Map();
  const seenMediaGroups = new Set();

  async function broadcastSlotToAllGroups(slotKey) {
    const groups = stateMgr.getActiveGroups();
    if (groups.length === 0) return { sentCount: 0 };
    const text = getPostForSlot(slotKey, stateMgr);
    let sentCount = 0;
    for (const grp of groups) {
      const res = await tgRequest("sendMessage", {
        chat_id: grp.chatId,
        text,
        parse_mode: "Markdown"
      });
      if (res && res.ok) sentCount++;
    }
    return { sentCount, text };
  }

  async function checkAndRunDailySchedule(nowOverride = null) {
    const now = nowOverride || getTashkentNow();
    const dateStr = now.dateStr;
    let hours = typeof now.hours === "number" ? now.hours : null;
    let minutes = typeof now.minutes === "number" ? now.minutes : null;
    if ((hours === null || minutes === null) && now.timeStr) {
      const [hStr, mStr] = String(now.timeStr).split(":");
      hours = parseInt(hStr, 10);
      minutes = parseInt(mStr, 10);
    }

    // Саат 08:00, 10:00, 15:00, 19:00 (00 минуттан 15 минутқа шекемги аралықта бот қосылса да жибереди)
    const scheduleHours = [
      { hour: 8, slotKey: "08:00" },
      { hour: 10, slotKey: "10:00" },
      { hour: 15, slotKey: "15:00" },
      { hour: 19, slotKey: "19:00" }
    ];

    const triggered = [];
    for (const item of scheduleHours) {
      if (hours === item.hour && minutes >= 0 && minutes <= 14) {
        if (!stateMgr.hasSentSchedule(dateStr, item.slotKey)) {
          const res = await broadcastSlotToAllGroups(item.slotKey);
          if (res.sentCount > 0) {
            stateMgr.markScheduleSent(dateStr, item.slotKey);
            triggered.push(item.slotKey);
          }
        }
      }
    }
    return triggered;
  }

  async function handleChatMemberUpdate(chatMemberUpdate) {
    if (!chatMemberUpdate || !chatMemberUpdate.chat) return;
    const chat = chatMemberUpdate.chat;
    if (chat.type === "group" || chat.type === "supergroup") {
      const newStatus = chatMemberUpdate.new_chat_member && chatMemberUpdate.new_chat_member.status;
      if (newStatus === "member" || newStatus === "administrator") {
        const isNew = stateMgr.registerGroup(chat.id, chat.title);
        if (isNew) {
          await tgRequest("sendMessage", {
            chat_id: chat.id,
            text:
              `✅ **«Pintok Apteka» Авто-ответчик ҳәм Мағлыўмат боты усы группаға табыслы орнатылды!**\n\n` +
              `🤖 **Бот ўазыйпалары:**\n` +
              `1️⃣ Дәри сорағанларға ҳәм рецепт жибергенлерге автомат жуўап қайтарады (Телефон: **${CONTACT_PHONE}**).\n` +
              `2️⃣ Ҳәр күни саат **08:00** де аптека ашылғаны ҳәм **09:00–16:00 бийпул доставка** ҳаққында хабар жибереди.\n` +
              `3️⃣ Ҳәр күни саат **10:00, 15:00 ҳәм 19:00** де дурыс аўқатланыў, витаминлер, Өзбекстанда сатылып атырған БАДлар ҳәм шөптен исленген дәрилер бойынша пайдалы мағлыўмат + сораў-жуўап жибереди.`,
            parse_mode: "Markdown"
          });
        }
      }
    }
  }

  async function handleGroupMessage(msg) {
    if (!msg || !msg.chat) return false;
    const chat = msg.chat;
    const isGroup = chat.type === "group" || chat.type === "supergroup";

    // Егер группадан хабар келсе, группаны автомат дизимге аламыз
    if (isGroup) {
      stateMgr.registerGroup(chat.id, chat.title);
    }

    // Ботлардың өз хабарларына жуўап бермеймиз
    if (msg.from && msg.from.is_bot) return true;

    // Жаңа ағза қосылған ямаса шыққан сервислик хабарларды өткерип жиберемиз
    if (msg.new_chat_members || msg.left_chat_member || msg.group_chat_created) {
      return true;
    }

    const rawText = (msg.text || msg.caption || "").trim();
    const cmd = rawText.split(/\s+/)[0].split("@")[0].toLowerCase();

    // Тексериў ҳәм басқарыў командалары (группада да, жеке чатта да ислейди)
    if (cmd === "/activate" || (isGroup && cmd === "/start")) {
      stateMgr.registerGroup(chat.id, chat.title);
      await tgRequest("sendMessage", {
        chat_id: chat.id,
        text:
          `✅ **«Pintok Apteka» группа боты актив ҳалатта ислеп тур!**\n\n` +
          `🕒 **Күнделикли кесте (Ташкент/Нөкис ўақты менен):**\n` +
          `• **08:00** — Жумыс басланыўы ҳәм 09:00–16:00 бийпул доставка хабарландырыўы\n` +
          `• **10:00** — Дурыс аўқатланыў ҳәм витаминлер (сораў-жуўап)\n` +
          `• **15:00** — Өзбекстанда сатылып атырған пайдалы БАДлар (сораў-жуўап)\n` +
          `• **19:00** — Шөптен исленген тәбийғый дәрилер ҳәм БАДлар (сораў-жуўап)\n\n` +
          `🧪 **Ҳәзир тексерип көриў командалары:**\n` +
          `• /test_8 — 08:00 деги хабарды шығарыў\n` +
          `• /test_10 — 10:00 деги мағлыўматты шығарыў\n` +
          `• /test_15 — 15:00 деги БАД мағлыўматын шығарыў\n` +
          `• /test_19 — 19:00 деги шөпли дәри мағлыўматын шығарыў\n` +
          `• /test_reply — Авто-ответчик жуўабын шығарыў`,
        parse_mode: "Markdown"
      });
      return true;
    }

    if (cmd === "/test_8") {
      await tgRequest("sendMessage", {
        chat_id: chat.id,
        text: MORNING_0800_TEXT,
        parse_mode: "Markdown"
      });
      return true;
    }

    if (cmd === "/test_10") {
      const text = getPostForSlot("10:00", stateMgr);
      await tgRequest("sendMessage", {
        chat_id: chat.id,
        text,
        parse_mode: "Markdown"
      });
      return true;
    }

    if (cmd === "/test_15") {
      const text = getPostForSlot("15:00", stateMgr);
      await tgRequest("sendMessage", {
        chat_id: chat.id,
        text,
        parse_mode: "Markdown"
      });
      return true;
    }

    if (cmd === "/test_19") {
      const text = getPostForSlot("19:00", stateMgr);
      await tgRequest("sendMessage", {
        chat_id: chat.id,
        text,
        parse_mode: "Markdown"
      });
      return true;
    }

    if (cmd === "/test_reply") {
      await tgRequest("sendMessage", {
        chat_id: chat.id,
        text: AUTO_REPLY_TEXT,
        parse_mode: "Markdown",
        reply_to_message_id: msg.message_id
      });
      return true;
    }

    if (!isGroup) {
      return false;
    }

    // Егер клиент бирден бир неше рецепт сүўретин альбом (media_group_id) қылып жиберсе — тек 1 мәрте жуўап қайтарамыз
    if (msg.media_group_id) {
      if (seenMediaGroups.has(msg.media_group_id)) {
        return true;
      }
      seenMediaGroups.add(msg.media_group_id);
      if (seenMediaGroups.size > 500) {
        const firstItem = seenMediaGroups.values().next().value;
        seenMediaGroups.delete(firstItem);
      }
    }

    // Хызметкердиң клиентке жазған қысқа жуўабына авто-ответчик қосылмаўы ушын
    if (isLikelyStaffReplyToCustomer(msg)) {
      return true;
    }

    // Дәри сораған текст ямаса рецепт (сүўрет, документ, даўыслы хабар, текст) келгенде авто-ответчик жуўап береди
    const hasContent = Boolean(rawText || msg.photo || msg.document || msg.voice);
    if (!hasContent) return true;

    const userId = (msg.from && msg.from.id) ? msg.from.id : 0;
    const cooldownKey = `${chat.id}:${userId}`;
    const lastRepliedAt = recentUserReplies.get(cooldownKey) || 0;
    const nowMs = Date.now();

    if (cooldownMs > 0 && nowMs - lastRepliedAt < cooldownMs) {
      return true;
    }
    recentUserReplies.set(cooldownKey, nowMs);

    await tgRequest("sendMessage", {
      chat_id: chat.id,
      text: AUTO_REPLY_TEXT,
      parse_mode: "Markdown",
      reply_to_message_id: msg.message_id
    });

    return true;
  }

  return {
    handleGroupMessage,
    handleChatMemberUpdate,
    checkAndRunDailySchedule,
    broadcastSlotToAllGroups,
    stateMgr
  };
}

let lastGroupUpdateId = 0;
async function pollGroupBotUpdates() {
  const groupBot = createGroupBotHandler();

  // Ҳәр 20 секундта саат 08:00, 10:00, 15:00, 19:00 болғанын тексерип турамыз
  setInterval(() => {
    groupBot.checkAndRunDailySchedule().catch(err => {
      console.error("Schedule check error:", err.message);
    });
  }, 20000);

  while (true) {
    try {
      await groupBot.checkAndRunDailySchedule();
      const data = await defaultGroupTgRequest("getUpdates", {
        offset: lastGroupUpdateId + 1,
        timeout: 20
      });

      if (data && data.ok && Array.isArray(data.result)) {
        for (const update of data.result) {
          lastGroupUpdateId = update.update_id;
          if (update.my_chat_member) {
            await groupBot.handleChatMemberUpdate(update.my_chat_member);
          }
          const incomingMsg = update.message || update.edited_message;
          if (incomingMsg) {
            await groupBot.handleGroupMessage(incomingMsg);
          }
        }
      }
    } catch (err) {
      console.error("Group Bot polling error:", err.message);
      await new Promise(r => setTimeout(r, 4000));
    }
  }
}

